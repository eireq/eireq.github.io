-- run this once in the supabase sql editor.
-- clean runs (mistakes = 0) are the onion board.
-- a run with any wrong letter is the mistake board.

create table if not exists public.onion_scores (
  id bigint generated by default as identity primary key,
  name text not null default 'a guy',
  wpm integer not null check (wpm between 0 and 400),
  onions integer not null default 0 check (onions between 0 and 200),
  mistakes integer not null check (mistakes between 0 and 999),
  board text not null check (board in ('onion', 'mistake')),
  created_at timestamptz not null default now(),
  check (
    (board = 'onion' and mistakes = 0)
    or (board = 'mistake' and mistakes > 0)
  )
);

create index if not exists onion_scores_board_wpm_idx
  on public.onion_scores (board, wpm desc, created_at asc);

alter table public.onion_scores enable row level security;

drop policy if exists "onion scores are publicly readable" on public.onion_scores;
create policy "onion scores are publicly readable"
on public.onion_scores
for select
to anon, authenticated
using (true);

drop policy if exists "onion scores are publicly insertable" on public.onion_scores;
create policy "onion scores are publicly insertable"
on public.onion_scores
for insert
to anon, authenticated
with check (
  char_length(name) between 1 and 30
  and wpm between 0 and 400
  and onions between 0 and 200
  and mistakes between 0 and 999
  and (
    (board = 'onion' and mistakes = 0)
    or (board = 'mistake' and mistakes > 0)
  )
);
