-- cave flyer and roof run. run this once in the supabase sql editor.
-- safe to run again. it does not touch lane runner or flag quiz scores.

create table if not exists public.run_scores (
  id bigint generated by default as identity primary key,
  game text not null check (game in ('cave', 'cave-slow', 'cave-glide', 'cave-random', 'roof')),
  name text not null default 'a guy',
  score integer not null check (score >= 0),
  distance integer not null default 0 check (distance >= 0),
  created_at timestamptz not null default now()
);

create index if not exists run_scores_game_score_idx
  on public.run_scores (game, score desc, created_at asc);

create index if not exists run_scores_game_created_idx
  on public.run_scores (game, created_at desc);

-- tables created before the extra cave modes only allow 'cave' and 'roof'.
alter table public.run_scores drop constraint if exists run_scores_game_check;
alter table public.run_scores
  add constraint run_scores_game_check
  check (game in ('cave', 'cave-slow', 'cave-glide', 'cave-random', 'roof'));

alter table public.run_scores enable row level security;

drop policy if exists "run scores are publicly readable" on public.run_scores;
create policy "run scores are publicly readable"
on public.run_scores
for select
to anon, authenticated
using (true);

drop policy if exists "run scores are publicly insertable" on public.run_scores;
create policy "run scores are publicly insertable"
on public.run_scores
for insert
to anon, authenticated
with check (
  game in ('cave', 'cave-slow', 'cave-glide', 'cave-random', 'roof')
  and char_length(name) between 1 and 16
  and score >= 0
  and distance >= 0
);

grant select, insert on public.run_scores to anon, authenticated;
grant usage, select on sequence public.run_scores_id_seq to anon, authenticated;

-- no update or delete policy. visitors can submit a run and read the board.
